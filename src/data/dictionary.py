"""Data dictionary, generated from the data and params so it never goes stale.

`python -m src.data.dictionary` writes docs/data_dictionary.md; `--check` compares.
"""

from __future__ import annotations

import argparse
import sys

import pandas as pd

from src.config import ROOT, load_params
from src.data.load import load_raw

DESCRIPTIONS = {
    "customerID": "Unique customer identifier.",
    "gender": "Customer's gender.",
    "SeniorCitizen": "1 if the customer is a senior citizen, 0 otherwise.",
    "Partner": "Whether the customer has a partner.",
    "Dependents": "Whether the customer has dependents.",
    "tenure": "Months subscribed, up to the time the data was taken.",
    "PhoneService": "Whether the customer subscribes to phone service.",
    "MultipleLines": "Whether the customer has more than one phone line.",
    "InternetService": "Type of internet service.",
    "OnlineSecurity": "Online security add-on.",
    "OnlineBackup": "Online backup add-on.",
    "DeviceProtection": "Device protection add-on.",
    "TechSupport": "Technical support add-on.",
    "StreamingTV": "TV streaming add-on.",
    "StreamingMovies": "Movie streaming add-on.",
    "Contract": "Contract type. Month-to-month is effectively no contract.",
    "PaperlessBilling": "Whether billing is paperless.",
    "PaymentMethod": "Payment method.",
    "MonthlyCharges": "Current monthly charge.",
    "TotalCharges": "Total charges accumulated up to the time the data was taken.",
    "Churn": "Observed churn status. Used as the label.",
}


def _type(col: str, sc: dict) -> str:
    if col == sc["id_column"]:
        return "string (unique)"
    if col in sc["int_columns"]:
        return "integer"
    if col in sc["float_columns"]:
        return "float"
    return "categorical"


def _values(col: str, raw: pd.DataFrame, sc: dict) -> str:
    """Describe the valid values of a column."""
    if col == sc["id_column"]:
        return "free-form, non-empty"
    if col in sc["float_columns"] or (col in sc["int_columns"] and raw[col].nunique() > 5):
        return ">= 0"
    return ", ".join(f"`{v}`" for v in sorted(raw[col].dropna().unique().tolist()))


def _role(col: str, params: dict) -> str:
    sc = params["schema"]
    if col == sc["id_column"]:
        return "id"
    if col == sc["label_column"]:
        return "label"
    if col in params["leakage"]["flagged_columns"]:
        return f"feature, leakage-prone (policy: {params['leakage']['policy']})"
    return "feature"


def build_dictionary(raw: pd.DataFrame, params: dict) -> str:
    sc = params["schema"]
    if set(DESCRIPTIONS) != set(sc["required_columns"]):
        raise ValueError("DESCRIPTIONS does not match schema.required_columns")
    lines = [
        "# Data dictionary",
        "",
        "Generated by `python -m src.data.dictionary`. Do not edit manually.",
        "",
        f"- **data_source:** `{params['data_source']}`",
        f"- **Label:** column `{sc['label_column']}`; `{sc['positive_label']}` = churned (positive class), "
        f"`{sc['negative_label']}` = retained.",
        f"- **Empty values:** only `{sc['nullable_when_tenure_zero']}` may be empty, and only when `tenure` = 0. "
        "No other column may be empty.",
        "",
        "| Column | Type | Valid values | Role | Description |",
        "|---|---|---|---|---|",
    ]
    for col in sc["required_columns"]:
        lines.append(
            f"| `{col}` | {_type(col, sc)} | {_values(col, raw, sc)} | {_role(col, params)} | {DESCRIPTIONS[col]} |"
        )
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    params = load_params()
    text = build_dictionary(load_raw("raw", params), params)
    path = ROOT / "docs" / "data_dictionary.md"
    if args.check:
        same = path.exists() and path.read_text(encoding="utf-8") == text
        print("data_dictionary.md MATCHES the generator" if same else "data_dictionary.md DIFFERS from the generator")
        return 0 if same else 1
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Input-drift monitoring: a reference distribution and thresholds for every model feature.

`build_reference` turns the train rows' feature matrix into the content of `reports/monitoring.json`: for
each feature its source columns, how its values are binned, the share of train rows in each bin, and the
PSI thresholds. `assess` compares a scoring-time feature matrix with that reference.

The file is generated by `make train` (never edited by hand) and is tied to the model's features in the same
spirit as the `E_PREDICT_FEATURES` check in predict.py:

- `check_alignment(monitoring, params)`: exactly the features and source columns that `features.build`
  produces for the current params (none missing, none extra), settings equal to `params.monitoring`, and
  every threshold present and valid. It needs no trained model, so tests and CI can run it.
- `check_model(monitoring, bundle)`: exactly the saved model's features, built from the same train rows.

If a feature is added, removed, or redefined, or the monitoring settings change, the checks fail until
`make train` writes the file again.

Three hashes keep thresholds and bins from changing unnoticed, following the pattern of `tuning.rule_lock`:

- `monitoring.rule_lock` in params.yaml is the sha256 of the rule (thresholds, bin counts, epsilon, minimum
  batch). Changing the rule without `python -m src.models.monitoring --write-lock` stops the run
  (`E_MONITOR_LOCK`), so a change is a visible, committed decision made before the file is rebuilt.
- `rule_hash` in the file records which rule built it; a difference from the lock is `E_MONITOR_STALE`.
- `content_hash` in the file is the sha256 of everything else in it, so an edit to a bin, a share, or a
  threshold is `E_MONITOR_HASH` even when the edited values are still valid.

Nothing here is random: the same train rows and settings give the same file, byte for byte.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import re
import sys
from pathlib import Path
from typing import TYPE_CHECKING

import numpy as np
import pandas as pd

from src.config import ROOT, load_params
from src.features.build import feature_names, feature_sources

if TYPE_CHECKING:  # train.py imports this module, so the import is only for type checkers
    from src.models.train import Bundle

RULE_VERSION = 1
KINDS = ("discrete", "continuous")
STATUSES = ("ok", "warn", "alert")
SETTING_KEYS = ("psi_warn", "psi_alert", "n_bins", "max_discrete_levels", "psi_eps", "min_rows")
# Thresholds are not listed: a missing or invalid one is E_MONITOR_THRESHOLDS, checked on its own.
ENTRY_KEYS = ("sources", "kind", "ref_props")


class MonitorError(ValueError):
    """The monitoring file or its input is invalid. `code` is stable for tests and the CLI."""

    def __init__(self, code: str, message: str):
        super().__init__(f"{code}: {message}")
        self.code = code
        self.message = message


# --- the locked rule and the content hash ----------------------------------------------------------
def settings_of(params: dict) -> dict:
    """The monitoring settings that shape the file (everything in the block except the lock itself)."""
    return {k: v for k, v in params["monitoring"].items() if k != "rule_lock"}


def rule_spec(params: dict) -> dict:
    """Everything that determines thresholds and bins, in a canonical form."""
    cfg = params["monitoring"]
    return {"version": RULE_VERSION, **{k: cfg[k] for k in SETTING_KEYS}}


def _sha256(obj) -> str:
    blob = json.dumps(obj, sort_keys=True, separators=(",", ":"), allow_nan=False)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def rule_hash(params: dict) -> str:
    return _sha256(rule_spec(params))


def verify_lock(params: dict) -> str:
    """Stop unless `monitoring.rule_lock` matches the rule actually in force. Returns the rule hash."""
    actual = rule_hash(params)
    if params["monitoring"]["rule_lock"] != actual:
        raise MonitorError(
            "E_MONITOR_LOCK",
            "monitoring.rule_lock does not match the monitoring rule in params.yaml "
            "(thresholds, n_bins, max_discrete_levels, psi_eps, or min_rows changed). "
            "If the change is intended, run `python -m src.models.monitoring --write-lock`, "
            "commit it, and then run `make train`.",
        )
    return actual


def content_hash(monitoring: dict) -> str:
    """sha256 of the whole file except `content_hash` itself (key order does not matter)."""
    return _sha256({k: v for k, v in monitoring.items() if k != "content_hash"})


def seal(monitoring: dict) -> dict:
    """Copy of `monitoring` with `content_hash` set (last key). Call again after any change to the content."""
    sealed = {k: v for k, v in monitoring.items() if k != "content_hash"}
    sealed["content_hash"] = content_hash(sealed)
    return sealed


# --- binning and PSI -----------------------------------------------------------------------------
def _n_bins(spec: dict) -> int:
    """Discrete: one bin per level plus an "other" bin. Continuous: one more bin than edges."""
    return len(spec["levels"]) + 1 if spec["kind"] == "discrete" else len(spec["edges"]) + 1


def _bin_index(values: np.ndarray, spec: dict) -> np.ndarray:
    """Bin of every value. Discrete: position in `levels`, or the last bin for a level never seen in training.

    Continuous: bins (-inf, e0], (e0, e1], ..., (e_last, inf), so values outside the train range land in an
    end bin instead of being dropped.
    """
    if spec["kind"] == "discrete":
        levels = np.asarray(spec["levels"], dtype="float64")
        hit = values[:, None] == levels[None, :]
        return np.where(hit.any(axis=1), hit.argmax(axis=1), len(levels))
    return np.searchsorted(np.asarray(spec["edges"], dtype="float64"), values, side="left")


def _shares(values: np.ndarray, spec: dict) -> list[float]:
    counts = np.bincount(_bin_index(values, spec), minlength=_n_bins(spec))
    return (counts / len(values)).tolist()


def _psi(ref: np.ndarray, cur: np.ndarray, eps: float) -> float:
    """Population stability index; shares are floored at `eps` so an empty bin stays finite."""
    r, c = np.clip(ref, eps, None), np.clip(cur, eps, None)
    return float(np.sum((c - r) * np.log(c / r)))


def _mismatch(expected, got) -> str:
    expected, got = list(expected), list(got)
    missing = [n for n in expected if n not in got]
    extra = [n for n in got if n not in expected]
    return f"missing: {missing}; extra: {extra}"


# --- build ---------------------------------------------------------------------------------------
def build_reference(X_train: pd.DataFrame, params: dict, *, train_hash: str) -> dict:
    """Reference distribution and thresholds for every feature, from the train rows only.

    A feature with at most `monitoring.max_discrete_levels` distinct train values is monitored level by level;
    any other feature is binned at its train quantiles (`monitoring.n_bins`). The choice depends on the data,
    not on a list of feature names, so a new feature is covered without editing this module.
    """
    lock = verify_lock(params)
    cfg = params["monitoring"]
    if len(X_train) == 0:
        raise MonitorError("E_MONITOR_ROWS", "train data is empty")
    if list(map(str, X_train.columns)) != feature_names(params):
        raise MonitorError("E_MONITOR_FEATURES", "current features do not match the train features")
    sources = feature_sources(params)
    quantiles = np.linspace(0.0, 1.0, cfg["n_bins"] + 1)[1:-1]
    features = {}
    for name in map(str, X_train.columns):
        v = X_train[name].to_numpy(dtype="float64")
        levels = np.unique(v)
        if len(levels) <= cfg["max_discrete_levels"]:
            spec = {"kind": "discrete", "levels": levels.tolist()}
        else:
            spec = {"kind": "continuous", "edges": np.unique(np.quantile(v, quantiles)).tolist()}
        features[name] = {
            "sources": list(sources[name]),
            **spec,
            "ref_props": _shares(v, spec),
            "psi_warn": cfg["psi_warn"],
            "psi_alert": cfg["psi_alert"],
        }
    reference = {
        "data_source": params["data_source"],
        "rule_hash": lock,
        "settings": settings_of(params),
        "reference": {"rows": int(len(X_train)), "train_data_hash": train_hash},
        "features": features,
    }
    return seal(reference)


# --- file ----------------------------------------------------------------------------------------
def dumps(monitoring: dict) -> str:
    return json.dumps(monitoring, indent=2, allow_nan=False) + "\n"


def write(monitoring: dict, path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dumps(monitoring), encoding="utf-8", newline="\n")
    return path


def load(path) -> dict:
    path = Path(path)
    if not path.is_file():
        raise MonitorError("E_MONITOR_FILE", f"{path.name} does not exist; run `make train`")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise MonitorError("E_MONITOR_FILE", f"{path.name} cannot be read as JSON: {e}") from e
    return data


# --- validation ----------------------------------------------------------------------------------
def _number(x) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def _is_number_list(x) -> bool:
    return isinstance(x, list) and all(_number(v) for v in x)


def _features(monitoring) -> dict:
    """The `features` mapping, after the top-level shape has been checked."""
    if not isinstance(monitoring, dict):
        raise MonitorError("E_MONITOR_FILE", "monitoring content must be a mapping")
    missing = [k for k in ("settings", "reference", "features") if k not in monitoring]
    if missing:
        raise MonitorError("E_MONITOR_FILE", f"missing keys: {missing}")
    feats = monitoring["features"]
    if not isinstance(feats, dict) or not feats or not all(isinstance(e, dict) for e in feats.values()):
        raise MonitorError("E_MONITOR_FILE", "`features` must be a non-empty mapping of feature to entry")
    return feats


def _check_thresholds(name: str, entry: dict) -> None:
    warn, alert = entry.get("psi_warn"), entry.get("psi_alert")
    if not (_number(warn) and _number(alert) and 0 < warn < alert):
        msg = f"{name}: psi_warn and psi_alert must be numbers with 0 < psi_warn < psi_alert"
        raise MonitorError("E_MONITOR_THRESHOLDS", msg)


def _check_reference(name: str, entry: dict) -> None:
    kind = entry.get("kind")
    if kind not in KINDS:
        raise MonitorError("E_MONITOR_REFERENCE", f"{name}: kind must be one of {list(KINDS)}")
    grid = entry.get("levels" if kind == "discrete" else "edges")
    if not _is_number_list(grid) or not grid or not np.all(np.diff(grid) > 0):
        msg = f"{name}: levels/edges must be a non-empty, strictly increasing list of numbers"
        raise MonitorError("E_MONITOR_REFERENCE", msg)
    props = entry.get("ref_props")
    ok = _is_number_list(props) and len(props) == _n_bins(entry)
    ok = ok and all(0 <= p <= 1 for p in props) and abs(sum(props) - 1.0) <= 1e-9
    if not ok:
        msg = f"{name}: ref_props must hold one share per bin, each in [0, 1], summing to one"
        raise MonitorError("E_MONITOR_REFERENCE", msg)


def validate(monitoring: dict) -> None:
    """The file is complete, valid, and unedited since it was written (no params or model needed)."""
    feats = _features(monitoring)
    settings = monitoring["settings"]
    if not isinstance(settings, dict) or any(k not in settings for k in SETTING_KEYS):
        raise MonitorError("E_MONITOR_FILE", f"settings must contain {list(SETTING_KEYS)}")
    ref = monitoring["reference"]
    if not isinstance(ref, dict) or not ref.get("train_data_hash"):
        raise MonitorError("E_MONITOR_FILE", "reference.train_data_hash is missing")
    if not isinstance(monitoring.get("rule_hash"), str):
        raise MonitorError("E_MONITOR_FILE", "rule_hash is missing")
    for name, entry in feats.items():
        absent = [k for k in ENTRY_KEYS if k not in entry]
        if absent:
            raise MonitorError("E_MONITOR_FILE", f"{name}: missing keys {absent}")
        _check_thresholds(name, entry)
        _check_reference(name, entry)
    if monitoring.get("content_hash") != content_hash(monitoring):
        msg = "content_hash is missing or wrong: the file was edited after it was written; run `make train`"
        raise MonitorError("E_MONITOR_HASH", msg)


def check_alignment(monitoring: dict, params: dict) -> None:
    """The file covers exactly the features of the current params, with the current settings.

    Order of checks: the lock, feature set, source columns, settings and rule hash, then every entry
    (thresholds, reference, content hash) and last that the thresholds equal the configured ones.
    """
    lock = verify_lock(params)
    feats = _features(monitoring)
    expected = feature_names(params)
    if set(feats) != set(expected):
        msg = f"monitoring does not cover the model's features ({_mismatch(expected, feats)})"
        raise MonitorError("E_MONITOR_FEATURES", msg)
    sources = feature_sources(params)
    changed = [n for n in expected if feats[n].get("sources") != list(sources[n])]
    if changed:
        msg = f"source columns differ from the feature definitions: {changed}"
        raise MonitorError("E_MONITOR_SOURCES", msg)
    if monitoring["settings"] != settings_of(params) or monitoring.get("rule_hash") != lock:
        msg = "built with a different monitoring rule than params.yaml; run `make train`"
        raise MonitorError("E_MONITOR_STALE", msg)
    validate(monitoring)
    want = (params["monitoring"]["psi_warn"], params["monitoring"]["psi_alert"])
    off = [n for n, e in feats.items() if (e["psi_warn"], e["psi_alert"]) != want]
    if off:
        raise MonitorError("E_MONITOR_THRESHOLDS", f"thresholds differ from params.monitoring: {off}")


def check_model(monitoring: dict, bundle: Bundle) -> None:
    """The file covers exactly the saved model's features and was built from the same train rows."""
    feats = _features(monitoring)
    names = list(map(str, bundle.model.feature_names))
    if set(feats) != set(names):
        msg = f"monitoring does not cover the model's features ({_mismatch(names, feats)})"
        raise MonitorError("E_MONITOR_FEATURES", msg)
    if monitoring["reference"].get("train_data_hash") != bundle.model.train_hash:
        msg = "built from different train rows than the saved model; run `make train`"
        raise MonitorError("E_MONITOR_STALE", msg)


# --- assessment ----------------------------------------------------------------------------------
def assess(X: pd.DataFrame, monitoring: dict) -> pd.DataFrame:
    """PSI and status of every feature for a scoring-time feature matrix (output of `build_features`).

    Returns a DataFrame indexed by feature with `psi` and `status` (`ok`, `warn`, or `alert`). A batch with
    fewer than `settings.min_rows` rows is refused: PSI on a handful of rows is mostly noise.
    """
    validate(monitoring)
    feats = monitoring["features"]
    cols = list(map(str, X.columns))
    if set(cols) != set(feats):
        msg = f"input features do not match the monitoring features ({_mismatch(feats, cols)})"
        raise MonitorError("E_MONITOR_FEATURES", msg)
    min_rows = monitoring["settings"]["min_rows"]
    if len(X) < min_rows:
        raise MonitorError("E_MONITOR_ROWS", f"{len(X)} rows is below settings.min_rows ({min_rows})")
    eps = monitoring["settings"]["psi_eps"]
    rows = []
    for name, entry in feats.items():
        v = X[name].to_numpy(dtype="float64")
        if not np.isfinite(v).all():
            raise MonitorError("E_MONITOR_INPUT", f"{name}: values must be finite")
        psi = _psi(np.asarray(entry["ref_props"], dtype="float64"), np.asarray(_shares(v, entry)), eps)
        status = "alert" if psi >= entry["psi_alert"] else "warn" if psi >= entry["psi_warn"] else "ok"
        rows.append((name, psi, status))
    return pd.DataFrame(rows, columns=["feature", "psi", "status"]).set_index("feature")


# --- command line --------------------------------------------------------------------------------
_LOCK_LINE = re.compile(r'^(\s*rule_lock:\s*)"[^"]*"(.*)$', re.MULTILINE)


def write_lock(params_path: Path, new_hash: str) -> bool:
    """Write `new_hash` into the `rule_lock` line of the `monitoring` block. False if no such line."""
    text = params_path.read_text(encoding="utf-8")
    block = re.search(r"^monitoring:", text, re.MULTILINE)
    if block is None:
        return False
    head, tail = text[: block.start()], text[block.start() :]
    tail, n = _LOCK_LINE.subn(lambda m: f'{m.group(1)}"{new_hash}"{m.group(2)}', tail, count=1)
    if n != 1:
        return False
    params_path.write_text(head + tail, encoding="utf-8", newline="\n")
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Check reports/monitoring.json against the model's features")
    g = ap.add_mutually_exclusive_group()
    g.add_argument(
        "--require-model",
        action="store_true",
        help="fail when artifacts/model.joblib is missing (default: check against params.yaml only)",
    )
    g.add_argument(
        "--write-lock",
        action="store_true",
        help="write the current rule hash into monitoring.rule_lock in params.yaml",
    )
    args = ap.parse_args(argv)
    params = load_params()
    if args.write_lock:
        h = rule_hash(params)
        if not write_lock(ROOT / "params.yaml", h):
            print('monitoring: no `rule_lock: "..."` line in the monitoring block of params.yaml')
            return 2
        print(f"monitoring: rule_lock written: {h}")
        return 0
    bundle_path = ROOT / params["paths"]["artifacts_dir"] / "model.joblib"
    try:
        monitoring = load(ROOT / params["paths"]["monitoring"])
        check_alignment(monitoring, params)
        if bundle_path.is_file():
            from src.models.train import load_bundle

            check_model(monitoring, load_bundle(bundle_path))
            against = "params and saved model"
        elif args.require_model:
            raise MonitorError("E_MONITOR_FILE", f"{bundle_path.name} does not exist; run `make train`")
        else:
            against = "params only (no saved model found)"
    except MonitorError as e:
        print(f"{e.code}: {e.message}")
        return 1
    print(f"features={len(monitoring['features'])} checked against {against}")
    print(f"rule_hash={monitoring['rule_hash'][:16]} content_hash={monitoring['content_hash'][:16]}")
    print("MONITORING OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
